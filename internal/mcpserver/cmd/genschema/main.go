// Command genschema compiles schemas/spawn.input.json into the spawn input
// schema this package publishes.
//
// The schema is one flat object, so unlike the messaging and workflow
// generators there is nothing to compile into tables: this command exists to
// put the file inside the binary. It emits the schema verbatim, which the
// spawn tool publishes as its input schema, and the two tables the packages'
// tests read.
//
// It runs from internal/mcpserver (go generate sets the working directory to
// the directory of the file holding the directive), so every path arrives on
// the command line and is resolved relative to that directory.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"
)

type property struct {
	Type  string `json:"type"`
	Items *struct {
		Type string `json:"type"`
	} `json:"items"`
	Description string   `json:"description"`
	Surfaces    []string `json:"x-avenor-surfaces"`
}

type inputSchema struct {
	Properties map[string]property `json:"properties"`
	Required   []string            `json:"required"`
}

func main() {
	inputPath := flag.String("input", "", "path to the spawn input schema")
	outPath := flag.String("out", "", "path to the generated Go file")
	pkg := flag.String("pkg", "", "package name for the generated file")
	flag.Parse()

	for name, value := range map[string]string{"input": *inputPath, "out": *outPath, "pkg": *pkg} {
		if value == "" {
			fmt.Fprintf(os.Stderr, "genschema: -%s is required\n", name)
			os.Exit(2)
		}
	}

	raw, err := os.ReadFile(*inputPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "genschema: read %s: %v\n", *inputPath, err)
		os.Exit(1)
	}
	var schema inputSchema
	if err := json.Unmarshal(raw, &schema); err != nil {
		fmt.Fprintf(os.Stderr, "genschema: parse %s: %v\n", *inputPath, err)
		os.Exit(1)
	}
	if len(schema.Properties) == 0 {
		fmt.Fprintf(os.Stderr, "genschema: %s declares no properties\n", *inputPath)
		os.Exit(1)
	}

	names := make([]string, 0, len(schema.Properties))
	for name := range schema.Properties {
		names = append(names, name)
	}
	sort.Strings(names)

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by internal/mcpserver/cmd/genschema; DO NOT EDIT.\n\npackage %s\n", *pkg)
	fmt.Fprintf(&b, "\n// spawnInputSchemaJSON is schemas/spawn.input.json verbatim: the one place a\n")
	fmt.Fprintf(&b, "// spawn field's name, type, and description is written. The spawn tool publishes\n")
	fmt.Fprintf(&b, "// it as its input schema.\nconst spawnInputSchemaJSON = %s\n", strconv.Quote(string(raw)))

	fmt.Fprintf(&b, "\n// spawnFieldDescriptions is each spawn input property's canonical description,\n")
	fmt.Fprintf(&b, "// keyed by the property name the schema declares.\nvar spawnFieldDescriptions = map[string]string{\n")
	for _, name := range names {
		fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(name), strconv.Quote(schema.Properties[name].Description))
	}
	fmt.Fprintf(&b, "}\n")

	fmt.Fprintf(&b, "\n// spawnFieldSurfaces names the surfaces that publish each property, so a test\n")
	fmt.Fprintf(&b, "// can hold every surface to the schema instead of to a remembered list.\nvar spawnFieldSurfaces = map[string][]string{\n")
	for _, name := range names {
		surfaces := append([]string(nil), schema.Properties[name].Surfaces...)
		sort.Strings(surfaces)
		quoted := make([]string, len(surfaces))
		for i, surface := range surfaces {
			quoted[i] = strconv.Quote(surface)
		}
		fmt.Fprintf(&b, "\t%s: {%s},\n", strconv.Quote(name), strings.Join(quoted, ", "))
	}
	fmt.Fprintf(&b, "}\n")

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		fmt.Fprintf(os.Stderr, "genschema: format generated source: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*outPath, formatted, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "genschema: write %s: %v\n", *outPath, err)
		os.Exit(1)
	}
}
