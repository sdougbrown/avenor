// Command genschema compiles the shared schema files into internal/messaging's
// generated Go artifacts: the two input JSON Schemas as string constants, the
// flat object schema each MCP surface publishes, the per-action applicability
// tables, the repair templates, the outcome rows with their render templates,
// and the peers `last` templates.
//
// It runs from internal/messaging (go generate sets the working directory to
// the directory of the file holding the directive), so every input path is
// passed explicitly by the directive and resolved relative to that directory.
package main

import (
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"reflect"
	"sort"
	"strconv"
	"strings"
)

type applicabilityEntry struct {
	Permitted []string          `json:"permitted"`
	Required  []string          `json:"required"`
	Types     map[string]string `json:"types"`
}

type schemaProperty struct {
	Const     string `json:"const"`
	Type      string `json:"type"`
	MinLength int    `json:"minLength"`
	MaxLength int    `json:"maxLength"`
	Pattern   string `json:"pattern"`
	Minimum   *int64 `json:"minimum"`
	Maximum   *int64 `json:"maximum"`
}

type inputSchema struct {
	OneOf []struct {
		Properties map[string]schemaProperty `json:"properties"`
	} `json:"oneOf"`
}

type propertyConstraints struct {
	MinLength  int
	MaxLength  int
	Pattern    string
	Minimum    int64
	HasMinimum bool
	Maximum    int64
	HasMaximum bool
}

type conformanceFixture struct {
	Repairs            map[string]string             `json:"repairs"`
	Applicability      map[string]applicabilityEntry `json:"applicability"`
	PeersApplicability map[string]applicabilityEntry `json:"peers_applicability"`
}

type outcomeRow struct {
	Outcome                string            `json:"outcome"`
	Source                 string            `json:"source"`
	MayHaveBeenTransmitted bool              `json:"mayHaveBeenTransmitted"`
	Terminal               bool              `json:"terminal"`
	ReuseMessageID         bool              `json:"reuseMessageId"`
	Fields                 []string          `json:"fields"`
	Render                 map[string]string `json:"render"`
}

type outcomeFixture struct {
	Outcomes  []outcomeRow        `json:"outcomes"`
	Matrix    map[string][]string `json:"matrix"`
	PeersLast map[string]string   `json:"peers_last"`
}

func main() {
	var (
		messageInput   = flag.String("message-input", "", "path to schemas/message.input.json")
		peersInput     = flag.String("peers-input", "", "path to schemas/peers.input.json")
		messageFlatOut = flag.String("message-flat-out", "", "path to write the flat message input schema")
		peersFlatOut   = flag.String("peers-flat-out", "", "path to write the flat peers input schema")
		conformance    = flag.String("conformance", "", "path to schemas/message_route.conformance.json")
		outcome        = flag.String("outcome", "", "path to schemas/message.outcome.json")
		out            = flag.String("out", "schema.gen.go", "output file")
	)
	flag.Parse()
	for name, value := range map[string]string{
		"-message-input":    *messageInput,
		"-peers-input":      *peersInput,
		"-message-flat-out": *messageFlatOut,
		"-peers-flat-out":   *peersFlatOut,
		"-conformance":      *conformance,
		"-outcome":          *outcome,
		"-out":              *out,
	} {
		if value == "" {
			fail("missing required flag %s", name)
		}
	}

	messageSchema := readFile(*messageInput)
	peersSchema := readFile(*peersInput)
	messageFlat, err := flattenInput(messageSchema, messageFlatSchemaMeta)
	if err != nil {
		fail("flatten %s: %v", *messageInput, err)
	}
	peersFlat, err := flattenInput(peersSchema, peersFlatSchemaMeta)
	if err != nil {
		fail("flatten %s: %v", *peersInput, err)
	}
	if err := os.WriteFile(*messageFlatOut, messageFlat, 0o644); err != nil {
		fail("write %s: %v", *messageFlatOut, err)
	}
	if err := os.WriteFile(*peersFlatOut, peersFlat, 0o644); err != nil {
		fail("write %s: %v", *peersFlatOut, err)
	}

	var conformanceDoc conformanceFixture
	mustDecode(*conformance, &conformanceDoc)
	var outcomeDoc outcomeFixture
	mustDecode(*outcome, &outcomeDoc)

	source, err := generate(messageSchema, peersSchema, messageFlat, peersFlat, conformanceDoc, outcomeDoc)
	if err != nil {
		fail("%v", err)
	}
	formatted, err := format.Source([]byte(source))
	if err != nil {
		fail("gofmt: %v", err)
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		fail("write %s: %v", *out, err)
	}
	fmt.Fprintf(os.Stderr, "generated %s\n", *out)
}

func generate(messageSchema, peersSchema, messageFlat, peersFlat []byte, conformance conformanceFixture, outcome outcomeFixture) (string, error) {
	messageConstraints, err := constraintsFromSchema(messageSchema)
	if err != nil {
		return "", err
	}
	peersConstraints, err := constraintsFromSchema(peersSchema)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("// Code generated by internal/messaging/cmd/genschema; DO NOT EDIT.\n\n")
	b.WriteString("package messaging\n\n")

	fmt.Fprintf(&b, "// messageInputSchemaJSON is schemas/message.input.json verbatim.\nconst messageInputSchemaJSON = %s\n\n", strconv.Quote(string(messageSchema)))
	fmt.Fprintf(&b, "// peersInputSchemaJSON is schemas/peers.input.json verbatim.\nconst peersInputSchemaJSON = %s\n\n", strconv.Quote(string(peersSchema)))
	fmt.Fprintf(&b, "// messageInputFlatSchemaJSON is schemas/message.input.flat.json verbatim: the flat\n// object schema MCP surfaces publish, compiled from the per-action union.\nconst messageInputFlatSchemaJSON = %s\n\n", strconv.Quote(string(messageFlat)))
	fmt.Fprintf(&b, "// peersInputFlatSchemaJSON is schemas/peers.input.flat.json verbatim: the flat\n// object schema MCP surfaces publish, compiled from the per-action union.\nconst peersInputFlatSchemaJSON = %s\n\n", strconv.Quote(string(peersFlat)))

	b.WriteString("// repairsTemplates is the per-error-code render template table.\nvar repairsTemplates = map[string]string{\n")
	for _, code := range sortedKeys(conformance.Repairs) {
		fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(code), strconv.Quote(conformance.Repairs[code]))
	}
	b.WriteString("}\n\n")

	writeApplicability(&b, "messageApplicability", "schemas/message_route.conformance.json's applicability map", conformance.Applicability, messageConstraints)
	writeApplicability(&b, "peersApplicability", "schemas/message_route.conformance.json's peers_applicability map", conformance.PeersApplicability, peersConstraints)

	b.WriteString("// outcomeRows is the outcome contract in declaration order.\nvar outcomeRows = []OutcomeRow{\n")
	for _, row := range outcome.Outcomes {
		if row.Source == "" {
			return "", fmt.Errorf("outcome %q has no source", row.Outcome)
		}
		fmt.Fprintf(&b, "\t{Outcome: %s, Source: %s, MayHaveBeenTransmitted: %t, Terminal: %t, ReuseMessageID: %t, Fields: %s, Render: map[string]string{",
			strconv.Quote(row.Outcome), strconv.Quote(row.Source), row.MayHaveBeenTransmitted, row.Terminal, row.ReuseMessageID, stringSlice(row.Fields))
		for _, action := range sortedKeys(row.Render) {
			fmt.Fprintf(&b, "%s: %s, ", strconv.Quote(action), strconv.Quote(row.Render[action]))
		}
		b.WriteString("}},\n")
	}
	b.WriteString("}\n\n")

	render, err := flattenRender(outcome)
	if err != nil {
		return "", err
	}
	b.WriteString("// outcomeRenderTemplates is keyed \"<action>:<outcome>\".\nvar outcomeRenderTemplates = map[string]string{\n")
	for _, key := range sortedKeys(render) {
		fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(key), strconv.Quote(render[key]))
	}
	b.WriteString("}\n\n")

	b.WriteString("// peersLastTemplates are the peers `last` render templates.\nvar peersLastTemplates = map[string]string{\n")
	for _, key := range sortedKeys(outcome.PeersLast) {
		fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(key), strconv.Quote(outcome.PeersLast[key]))
	}
	b.WriteString("}\n")

	return b.String(), nil
}

func flattenRender(outcome outcomeFixture) (map[string]string, error) {
	out := map[string]string{}
	for _, row := range outcome.Outcomes {
		for action, template := range row.Render {
			key := action + ":" + row.Outcome
			if _, ok := out[key]; ok {
				return nil, fmt.Errorf("render template %q declared twice", key)
			}
			out[key] = template
		}
	}
	// Every declared matrix pair must have exactly one template, and every
	// template must belong to a matrix pair: that is what makes the text total.
	keys := sortedKeys(out)
	for _, action := range sortedKeys(outcome.Matrix) {
		for _, name := range outcome.Matrix[action] {
			keys = remove(keys, action+":"+name)
		}
	}
	if len(keys) > 0 {
		return nil, fmt.Errorf("render templates outside the matrix: %s", strings.Join(keys, ", "))
	}
	for _, action := range sortedKeys(outcome.Matrix) {
		for _, name := range outcome.Matrix[action] {
			if out[action+":"+name] == "" {
				return nil, fmt.Errorf("matrix pair %q has no render template", action+":"+name)
			}
		}
	}
	return out, nil
}

func remove(values []string, target string) []string {
	out := values[:0]
	for _, value := range values {
		if value != target {
			out = append(out, value)
		}
	}
	return out
}

func writeApplicability(b *strings.Builder, name, description string, table map[string]applicabilityEntry, constraints map[string]map[string]propertyConstraints) {
	fmt.Fprintf(b, "// %s is %s.\nvar %s = map[string]ActionApplicability{\n", name, description, name)
	for _, action := range sortedKeys(table) {
		entry := table[action]
		for property, kind := range entry.Types {
			switch kind {
			case "string", "integer", "object":
			default:
				panic(fmt.Sprintf("%s: property %q declares unsupported type %q", action, property, kind))
			}
		}
		fmt.Fprintf(b, "\t%s: {Permitted: %s, Required: %s, Types: map[string]string{", strconv.Quote(action), stringSlice(entry.Permitted), stringSlice(entry.Required))
		for _, property := range sortedKeys(entry.Types) {
			fmt.Fprintf(b, "%s: %s, ", strconv.Quote(property), strconv.Quote(entry.Types[property]))
		}
		b.WriteString("}")
		if len(constraints[action]) > 0 {
			b.WriteString(", Constraints: map[string]PropertyConstraints{")
			for _, property := range sortedKeys(constraints[action]) {
				constraint := constraints[action][property]
				fmt.Fprintf(b, "%s: {", strconv.Quote(property))
				if constraint.MinLength > 0 {
					fmt.Fprintf(b, "MinLength: %d, ", constraint.MinLength)
				}
				if constraint.MaxLength > 0 {
					fmt.Fprintf(b, "MaxLength: %d, ", constraint.MaxLength)
				}
				if constraint.Pattern != "" {
					fmt.Fprintf(b, "Pattern: %s, ", strconv.Quote(constraint.Pattern))
				}
				if constraint.HasMinimum {
					fmt.Fprintf(b, "Minimum: %d, HasMinimum: true, ", constraint.Minimum)
				}
				if constraint.HasMaximum {
					fmt.Fprintf(b, "Maximum: %d, HasMaximum: true, ", constraint.Maximum)
				}
				b.WriteString("}, ")
			}
			b.WriteString("}")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
}

