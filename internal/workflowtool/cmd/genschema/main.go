// Command genschema compiles the shared workflow schema files into
// internal/workflowtool's generated Go artifacts: the input JSON Schema as a
// string constant, the flat object schema each MCP surface publishes, the
// per-action applicability tables, the enum and constraint tables, and the
// repair templates.
//
// It runs from internal/workflowtool (go generate sets the working directory to
// the directory of the file holding the directive), so every input path is
// passed explicitly by the directive and resolved relative to that directory.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"

	"github.com/sdougbrown/avenor/internal/flatgen"
)

type applicabilityEntry struct {
	Permitted []string          `json:"permitted"`
	Required  []string          `json:"required"`
	Types     map[string]string `json:"types"`
}

type schemaProperty struct {
	Const     string          `json:"const"`
	Type      string          `json:"type"`
	MinLength int             `json:"minLength"`
	MaxLength int             `json:"maxLength"`
	Pattern   string          `json:"pattern"`
	Minimum   *int64          `json:"minimum"`
	Maximum   *int64          `json:"maximum"`
	Enum      []string        `json:"enum"`
	Items     *schemaProperty `json:"items"`
}

type inputSchema struct {
	OneOf []struct {
		Properties map[string]schemaProperty `json:"properties"`
		Required   []string                  `json:"required"`
	} `json:"oneOf"`
}

type propertyConstraints struct {
	MinLength  int
	MaxLength  int
	Pattern    string
	Minimum    int64
	HasMinimum bool
	Maximum    int64
	HasMaximum bool
	ItemType   string
}

type conformanceFixture struct {
	Repairs       map[string]string             `json:"repairs"`
	Applicability map[string]applicabilityEntry `json:"applicability"`
}

func main() {
	var (
		input       = flag.String("input", "", "path to schemas/workflow.input.json")
		flatOut     = flag.String("flat-out", "", "path to write the flat workflow input schema")
		conformance = flag.String("conformance", "", "path to schemas/workflow_route.conformance.json")
		out         = flag.String("out", "schema.gen.go", "output file")
	)
	flag.Parse()
	for name, value := range map[string]string{
		"-input":       *input,
		"-flat-out":    *flatOut,
		"-conformance": *conformance,
		"-out":         *out,
	} {
		if value == "" {
			fail("missing required flag %s", name)
		}
	}

	schema := readFile(*input)
	flat, err := flatgen.Flatten(schema, flatgen.Meta{
		Title: "avenor_workflow flat input",
		ID:    "https://avenor.dev/schemas/workflow.input.flat.json",
		Description: "Flat input schema for the avenor_workflow tool, compiled from " +
			"schemas/workflow.input.json's per-action union so an MCP client publishes one " +
			"object whose property types survive: an integer stays an integer and an array " +
			"stays an array. Every action's properties appear here, so a field belonging to " +
			"another action is not a schema error. Per-action admission (required fields, " +
			"unknown properties, types, enums and limits) belongs to the router, which " +
			"answers a mismatch at once with the contract's typed invalid_request and its " +
			"repair text. Generated by internal/workflowtool/cmd/genschema; do not edit.",
	})
	if err != nil {
		fail("flatten %s: %v", *input, err)
	}
	if err := os.WriteFile(*flatOut, flat, 0o644); err != nil {
		fail("write %s: %v", *flatOut, err)
	}

	var conformanceDoc conformanceFixture
	mustDecode(*conformance, &conformanceDoc)

	source, err := generate(schema, flat, conformanceDoc)
	if err != nil {
		fail("%v", err)
	}
	formatted, err := format.Source([]byte(source))
	if err != nil {
		fail("gofmt: %v", err)
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		fail("write %s: %v", *out, err)
	}
	fmt.Fprintf(os.Stderr, "generated %s\n", *out)
}

func generate(schema, flat []byte, conformance conformanceFixture) (string, error) {
	constraints, enums, err := constraintsFromSchema(schema)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("// Code generated by internal/workflowtool/cmd/genschema; DO NOT EDIT.\n\n")
	b.WriteString("package workflowtool\n\n")

	fmt.Fprintf(&b, "// workflowInputSchemaJSON is schemas/workflow.input.json verbatim.\nconst workflowInputSchemaJSON = %s\n\n", strconv.Quote(string(schema)))
	fmt.Fprintf(&b, "// workflowInputFlatSchemaJSON is schemas/workflow.input.flat.json verbatim: the flat\n// object schema MCP surfaces publish, compiled from the per-action union.\nconst workflowInputFlatSchemaJSON = %s\n\n", strconv.Quote(string(flat)))

	b.WriteString("// repairsTemplates is the per-error-code render template table.\nvar repairsTemplates = map[string]string{\n")
	for _, code := range sortedKeys(conformance.Repairs) {
		fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(code), strconv.Quote(conformance.Repairs[code]))
	}
	b.WriteString("}\n\n")

	writeApplicability(&b, conformance.Applicability, constraints, enums)
	return b.String(), nil
}

func writeApplicability(b *strings.Builder, table map[string]applicabilityEntry, constraints map[string]map[string]propertyConstraints, enums map[string]map[string][]string) {
	b.WriteString("// workflowApplicability is schemas/workflow_route.conformance.json's applicability map.\nvar workflowApplicability = map[string]ActionApplicability{\n")
	for _, action := range sortedKeys(table) {
		entry := table[action]
		for property, kind := range entry.Types {
			switch kind {
			case "string", "integer", "object", "array", "json":
			default:
				panic(fmt.Sprintf("%s: property %q declares unsupported type %q", action, property, kind))
			}
		}
		fmt.Fprintf(b, "\t%s: {Permitted: %s, Required: %s, Types: map[string]string{", strconv.Quote(action), stringSlice(entry.Permitted), stringSlice(entry.Required))
		for _, property := range sortedKeys(entry.Types) {
			fmt.Fprintf(b, "%s: %s, ", strconv.Quote(property), strconv.Quote(entry.Types[property]))
		}
		b.WriteString("}")
		if len(enums[action]) > 0 {
			b.WriteString(", Enums: map[string][]string{")
			for _, property := range sortedKeys(enums[action]) {
				fmt.Fprintf(b, "%s: %s, ", strconv.Quote(property), stringSlice(enums[action][property]))
			}
			b.WriteString("}")
		}
		if len(constraints[action]) > 0 {
			b.WriteString(", Constraints: map[string]PropertyConstraints{")
			for _, property := range sortedKeys(constraints[action]) {
				constraint := constraints[action][property]
				fmt.Fprintf(b, "%s: {", strconv.Quote(property))
				if constraint.MinLength > 0 {
					fmt.Fprintf(b, "MinLength: %d, ", constraint.MinLength)
				}
				if constraint.MaxLength > 0 {
					fmt.Fprintf(b, "MaxLength: %d, ", constraint.MaxLength)
				}
				if constraint.Pattern != "" {
					fmt.Fprintf(b, "Pattern: %s, ", strconv.Quote(constraint.Pattern))
				}
				if constraint.HasMinimum {
					fmt.Fprintf(b, "Minimum: %d, HasMinimum: true, ", constraint.Minimum)
				}
				if constraint.HasMaximum {
					fmt.Fprintf(b, "Maximum: %d, HasMaximum: true, ", constraint.Maximum)
				}
				if constraint.ItemType != "" {
					fmt.Fprintf(b, "ItemType: %s, ", strconv.Quote(constraint.ItemType))
				}
				b.WriteString("}, ")
			}
			b.WriteString("}")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
}

// constraintsFromSchema reads each variant's string length, pattern, integer
// bounds, enum and array item type, so the compiled applicability table
// enforces the published schema's rules instead of restating them.
func constraintsFromSchema(raw []byte) (map[string]map[string]propertyConstraints, map[string]map[string][]string, error) {
	var schema inputSchema
	if err := json.Unmarshal(raw, &schema); err != nil {
		return nil, nil, fmt.Errorf("decode input schema: %w", err)
	}
	constraints := map[string]map[string]propertyConstraints{}
	enums := map[string]map[string][]string{}
	for _, variant := range schema.OneOf {
		action := variant.Properties["action"].Const
		if action == "" {
			continue
		}
		for property, spec := range variant.Properties {
			if property == "action" {
				continue
			}
			if len(spec.Enum) > 0 {
				if enums[action] == nil {
					enums[action] = map[string][]string{}
				}
				enums[action][property] = spec.Enum
			}
			if spec.MinLength == 0 && spec.MaxLength == 0 && spec.Pattern == "" && spec.Minimum == nil && spec.Maximum == nil && spec.Items == nil {
				continue
			}
			if constraints[action] == nil {
				constraints[action] = map[string]propertyConstraints{}
			}
			constraint := propertyConstraints{MinLength: spec.MinLength, MaxLength: spec.MaxLength, Pattern: spec.Pattern}
			if spec.Minimum != nil {
				constraint.Minimum = *spec.Minimum
				constraint.HasMinimum = true
			}
			if spec.Maximum != nil {
				constraint.Maximum = *spec.Maximum
				constraint.HasMaximum = true
			}
			if spec.Items != nil {
				constraint.ItemType = spec.Items.Type
			}
			constraints[action][property] = constraint
		}
	}
	return constraints, enums, nil
}

func stringSlice(values []string) string {
	if len(values) == 0 {
		return "nil"
	}
	quoted := make([]string, 0, len(values))
	for _, value := range values {
		quoted = append(quoted, strconv.Quote(value))
	}
	return "[]string{" + strings.Join(quoted, ", ") + "}"
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for key := range m {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

func readFile(path string) []byte {
	data, err := os.ReadFile(path)
	if err != nil {
		fail("read %s: %v", path, err)
	}
	return data
}

func mustDecode(path string, value any) {
	if err := json.Unmarshal(readFile(path), value); err != nil {
		fail("decode %s: %v", path, err)
	}
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "genschema: "+format+"\n", args...)
	os.Exit(1)
}
