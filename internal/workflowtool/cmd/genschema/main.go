// Command genschema compiles the shared workflow schema files into
// internal/workflowtool's generated Go artifacts: the input JSON Schema as a
// string constant, the flat object schema each MCP surface publishes, the
// per-action applicability tables, the enum and constraint tables, and the
// repair templates.
//
// It runs from internal/workflowtool (go generate sets the working directory to
// the directory of the file holding the directive), so every input path is
// passed explicitly by the directive and resolved relative to that directory.
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"

	"github.com/sdougbrown/avenor/internal/flatgen"
	"github.com/sdougbrown/avenor/internal/flatgen/genschema"
)

func main() {
	var (
		input       = flag.String("input", "", "path to schemas/workflow.input.json")
		flatOut     = flag.String("flat-out", "", "path to write the flat workflow input schema")
		conformance = flag.String("conformance", "", "path to schemas/workflow_route.conformance.json")
		out         = flag.String("out", "schema.gen.go", "output file")
	)
	flag.Parse()
	for name, value := range map[string]string{
		"-input":       *input,
		"-flat-out":    *flatOut,
		"-conformance": *conformance,
		"-out":         *out,
	} {
		if value == "" {
			genschema.Fail("missing required flag %s", name)
		}
	}

	schema := genschema.ReadFile(*input)
	flat, err := flatgen.Flatten(schema, flatgen.Meta{
		Title: "avenor_workflow flat input",
		ID:    "https://avenor.dev/schemas/workflow.input.flat.json",
		Description: "Flat input schema for the avenor_workflow tool, compiled from " +
			"schemas/workflow.input.json's per-action union so an MCP client publishes one " +
			"object whose property types survive: an integer stays an integer and an array " +
			"stays an array. Every action's properties appear here, so a field belonging to " +
			"another action is not a schema error. Per-action admission (required fields, " +
			"unknown properties, types, enums and limits) belongs to the router, which " +
			"answers a mismatch at once with the contract's typed invalid_request and its " +
			"repair text. Generated by internal/workflowtool/cmd/genschema; do not edit.",
	})
	if err != nil {
		genschema.Fail("flatten %s: %v", *input, err)
	}
	if err := os.WriteFile(*flatOut, flat, 0o644); err != nil {
		genschema.Fail("write %s: %v", *flatOut, err)
	}

	var conformanceDoc genschema.ConformanceFixture
	genschema.MustDecode(*conformance, &conformanceDoc)

	source, err := generate(schema, flat, conformanceDoc)
	if err != nil {
		genschema.Fail("%v", err)
	}
	formatted, err := format.Source([]byte(source))
	if err != nil {
		genschema.Fail("gofmt: %v", err)
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		genschema.Fail("write %s: %v", *out, err)
	}
	fmt.Fprintf(os.Stderr, "generated %s\n", *out)
}

func generate(schema, flat []byte, conformance genschema.ConformanceFixture) (string, error) {
	constraints, enums, err := genschema.ConstraintsFromSchema(schema)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("// Code generated by internal/workflowtool/cmd/genschema; DO NOT EDIT.\n\n")
	b.WriteString("package workflowtool\n\n")

	fmt.Fprintf(&b, "// workflowInputSchemaJSON is schemas/workflow.input.json verbatim.\nconst workflowInputSchemaJSON = %s\n\n", strconv.Quote(string(schema)))
	fmt.Fprintf(&b, "// workflowInputFlatSchemaJSON is schemas/workflow.input.flat.json verbatim: the flat\n// object schema MCP surfaces publish, compiled from the per-action union.\nconst workflowInputFlatSchemaJSON = %s\n\n", strconv.Quote(string(flat)))

	b.WriteString("// repairsTemplates is the per-error-code render template table.\nvar repairsTemplates = map[string]string{\n")
	for _, code := range genschema.SortedKeys(conformance.Repairs) {
		fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(code), strconv.Quote(conformance.Repairs[code]))
	}
	b.WriteString("}\n\n")

	genschema.WriteApplicability(&b, "workflowApplicability", "schemas/workflow_route.conformance.json's applicability map", conformance.Applicability, constraints, enums)
	return b.String(), nil
}
